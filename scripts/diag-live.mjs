import { chromium } from 'playwright-core'
const BASE='https://x13502239474-oss.github.io/python-academy/'
const b=await chromium.launch({executablePath:'C://Program Files\\Google\\Chrome\\Application\\chrome.exe',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']})
const p=await b.newPage()
p.on('console',m=>console.log('[console:'+m.type()+']',m.text().slice(0,250)))
p.on('pageerror',e=>console.log('[pageerror]',e.message.slice(0,300)))
p.on('requestfailed',r=>console.log('[reqfail]',r.url().slice(0,140),r.failure()?.errorText))
p.on('response',r=>{if(r.status()>=400)console.log('[http'+r.status()+']',r.url().slice(0,140))})
await p.goto(BASE,{waitUntil:'domcontentloaded',timeout:60000})
await p.waitForTimeout(8000)
console.log('--- body text (first 500) ---')
console.log((await p.locator('body').innerText()).slice(0,500))
console.log('--- h1 count:',await p.locator('h1').count())
console.log('--- #root html len:',(await p.locator('#root').innerHTML()).length)
await b.close()
